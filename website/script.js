document.addEventListener('DOMContentLoaded', () => {
    // 1. Navbar Scroll Effect
    const navbar = document.querySelector('.navbar');
    window.addEventListener('scroll', () => {
        if (window.scrollY > 50) {
            navbar.classList.add('scrolled');
        } else {
            navbar.classList.add('scrolled');
            navbar.classList.remove('scrolled');
        }
    });

    // Initial check
    if (window.scrollY > 50) {
        navbar.classList.add('scrolled');
    }

    // 2. OS Detection for Primary Download Button
    const osNameSpan = document.getElementById('os-name');
    const autoDownloadBtn = document.getElementById('auto-download-btn');

    let osName = "Windows";
    let downloadLink = "https://github.com/rzayevsahil/Shotera/releases/latest";

    const userAgent = window.navigator.userAgent.toLowerCase();
    if (userAgent.indexOf("mac") !== -1) {
        osName = "macOS";
    } else if (userAgent.indexOf("linux") !== -1 || userAgent.indexOf("ubuntu") !== -1) {
        osName = "Linux";
    }

    osNameSpan.textContent = osName;

    // 3. Intersection Observer for Fade-in Animations
    const observerOptions = {
        root: null,
        rootMargin: '0px',
        threshold: 0.1
    };

    const observer = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
                observer.unobserve(entry.target);
            }
        });
    }, observerOptions);

    document.querySelectorAll('.fade-in-up').forEach(element => {
        observer.observe(element);
    });

    // 4. Fetch Latest Release Assets from GitHub API for direct downloads
    fetch('https://api.github.com/repos/rzayevsahil/Shotera/releases/latest')
        .then(res => res.json())
        .then(data => {
            if (!data) return;

            // Dynamically set the latest version tag from GitHub release
            if (data.tag_name) {
                const versionStr = data.tag_name.startsWith('v') ? data.tag_name : `v${data.tag_name}`;
                const versionBadge = document.getElementById('latest-version-badge');
                if (versionBadge) {
                    versionBadge.textContent = versionStr;
                }
            }

            if (!data.assets) return;
            const assets = data.assets;

            let msiUrl = "", exeUrl = "", dmgUrl = "", tarUrl = "", debUrl = "", appImageUrl = "";
            let winCount = 0, macCount = 0, linuxCount = 0;

            assets.forEach(asset => {
                const name = asset.name.toLowerCase();
                if (name.endsWith('.msi')) {
                    msiUrl = asset.browser_download_url;
                    winCount += asset.download_count;
                }
                else if (name.endsWith('.exe')) {
                    exeUrl = asset.browser_download_url;
                    winCount += asset.download_count;
                }
                else if (name.endsWith('.dmg')) {
                    dmgUrl = asset.browser_download_url;
                    macCount += asset.download_count;
                }
                else if (name.endsWith('app.tar.gz')) {
                    tarUrl = asset.browser_download_url;
                    macCount += asset.download_count;
                }
                else if (name.endsWith('.deb')) {
                    debUrl = asset.browser_download_url;
                    linuxCount += asset.download_count;
                }
                else if (name.endsWith('.appimage')) {
                    appImageUrl = asset.browser_download_url;
                    linuxCount += asset.download_count;
                }
            });

            // Set hrefs to direct downloads
            if (msiUrl) document.getElementById('win-msi-btn').href = msiUrl;
            if (exeUrl) document.getElementById('win-exe-btn').href = exeUrl;
            if (dmgUrl) document.getElementById('mac-dmg-btn').href = dmgUrl;
            if (tarUrl) document.getElementById('mac-tar-btn').href = tarUrl;
            if (debUrl) document.getElementById('linux-deb-btn').href = debUrl;
            if (appImageUrl) document.getElementById('linux-appimage-btn').href = appImageUrl;

            // Set download counts
            document.getElementById('win-dl-count').textContent = winCount;
            document.getElementById('mac-dl-count').textContent = macCount;
            document.getElementById('linux-dl-count').textContent = linuxCount;

            // Set the dynamic hero button download link
            if (osName === "Windows" && msiUrl) autoDownloadBtn.href = msiUrl;
            else if (osName === "macOS" && dmgUrl) autoDownloadBtn.href = dmgUrl;
            else if (osName === "Linux" && debUrl) autoDownloadBtn.href = debUrl;
        })
        .catch(err => console.error("Failed to fetch GitHub releases:", err));

    // Fetch GitHub Stars
    fetch("https://api.github.com/repos/rzayevsahil/Shotera")
        .then(res => res.json())
        .then(data => {
            if (data.stargazers_count !== undefined) {
                const starBadge = document.getElementById('github-stars');
                const starCount = document.getElementById('star-count');
                if (starBadge && starCount) {
                    starCount.textContent = data.stargazers_count;
                    starBadge.style.display = "inline-flex";
                }
            }
        })
        .catch(err => console.error("Failed to fetch repo stars:", err));

    // 5. Language Switcher Dropdown Logic
    const langDropdown = document.getElementById('lang-dropdown');
    const langToggleBtn = document.getElementById('lang-toggle-btn');
    const currentLangText = document.getElementById('current-lang-text');
    const langOptions = document.querySelectorAll('.lang-option');
    const settingsImg = document.getElementById('settings-img');

    const langNames = {
        en: 'English',
        tr: 'Türkçe',
        az: 'Azərbaycan',
        ru: 'Русский',
        de: 'Deutsch'
    };

    // Detect system language or use saved
    let currentLang = localStorage.getItem('site_lang');
    if (!currentLang) {
        const userLang = navigator.language.toLowerCase();
        if (userLang.startsWith('de')) currentLang = 'de';
        else if (userLang.startsWith('ru')) currentLang = 'ru';
        else if (userLang.startsWith('az')) currentLang = 'az';
        else if (userLang.startsWith('tr')) currentLang = 'tr';
        else currentLang = 'en';
    }

    const setLanguage = (lang) => {
        currentLang = lang;
        localStorage.setItem('site_lang', lang);
        
        // Display active language text on button
        if (currentLangText) {
            currentLangText.textContent = langNames[lang] || 'English';
        }

        // Highlight active option in dropdown menu
        langOptions.forEach(opt => {
            if (opt.getAttribute('data-lang') === lang) {
                opt.classList.add('active');
            } else {
                opt.classList.remove('active');
            }
        });
        
        // Update document lang
        document.documentElement.lang = lang;
        
        // OS Modifier for shortcuts
        const modifier = osName === "macOS" ? "Cmd" : "Ctrl";
        
        // Update text nodes
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                let text = translations[lang][key];
                // dynamically replace the modifier key
                text = text.replace('{mod}', modifier);
                el.innerHTML = text;
            }
        });

        // Update settings image correctly depending on language
        if (settingsImg && translations[lang]['settings-img-src']) {
            settingsImg.src = translations[lang]['settings-img-src'];
        }
    };

    // Toggle Dropdown
    if (langToggleBtn && langDropdown) {
        langToggleBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            const isOpen = langDropdown.classList.contains('open');
            langDropdown.classList.toggle('open');
            langToggleBtn.setAttribute('aria-expanded', !isOpen);
        });

        // Click on option
        langOptions.forEach(opt => {
            opt.addEventListener('click', (e) => {
                e.stopPropagation();
                const selectedLang = opt.getAttribute('data-lang');
                if (selectedLang) {
                    setLanguage(selectedLang);
                }
                langDropdown.classList.remove('open');
                langToggleBtn.setAttribute('aria-expanded', 'false');
            });
        });

        // Close dropdown when clicking outside
        document.addEventListener('click', (e) => {
            if (!langDropdown.contains(e.target)) {
                langDropdown.classList.remove('open');
                langToggleBtn.setAttribute('aria-expanded', 'false');
            }
        });
    }

    // Initialize Language
    setLanguage(currentLang);

    // 6. Mobile Menu Logic
    const mobileBtn = document.getElementById('mobile-menu-btn');
    const navLinks = document.getElementById('nav-links');

    if (mobileBtn && navLinks) {
        const navbar = document.querySelector('.navbar');

        mobileBtn.addEventListener('click', () => {
            navLinks.classList.toggle('active');
            if (navbar) navbar.classList.toggle('menu-open');
        });

        // Close menu when clicking a link
        navLinks.querySelectorAll('a').forEach(link => {
            link.addEventListener('click', () => {
                navLinks.classList.remove('active');
                if (navbar) navbar.classList.remove('menu-open');
            });
        });
    }
});
